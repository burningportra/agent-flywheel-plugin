#!/usr/bin/env node

/**
 * Translate the Claude Code hooks/hooks.json contract into the AGY
 * hooks.json + wrapper-script contract (bead agent-flywheel-plugin-dm1).
 *
 * Differences this module owns (see agy/manifest.json hooks[]):
 *   - AGY hooks.json is a flat map of named hooks at the plugin root; the
 *     Claude { "hooks": { Event: [...] } } wrapper key does not exist.
 *   - AGY tool matchers name AGY tools: run_command, not Bash.
 *   - AGY has no `if` filter, no SubagentStop, no compaction event; the
 *     wrapper scripts apply the guard patterns themselves.
 *   - Every handler must print a JSON object on stdout. Wrappers print
 *     {"decision":"allow"} / {"decision":"deny","reason":"..."} for
 *     PreToolUse, {"injectSteps":[...]} for SessionStart, and {} for Stop —
 *     never decision:"continue", so a Stop hook cannot trap the loop.
 *   - Handler cwd is the directory containing hooks.json, so wrappers
 *     resolve helpers next to themselves and reference repo scripts by
 *     absolute path.
 */

const GUARD_PATTERNS = [
  /\bam\s+doctor\s+(repair|archive-normalize|reconstruct|restore|fix|fix-orphan-refs|pack-archive)\b/i,
  /\b(rm|unlink)\b[^\n;&|]*(\.mailbox\.activity\.lock|storage\.sqlite3\.activity\.lock)/i,
];

const DENY_REASON =
  "Agent Mail guard: refusing a mutating `am doctor` maintenance command or " +
  "activity-lock deletion while the service may be running. Stop the owning " +
  "runtime first, or use flywheel_remediate({ checkName: \"agent_mail_liveness\", " +
  "mode: \"execute\" }). Set FLYWHEEL_ALLOW_AM_DOCTOR=1 to break glass.";

const STARTUP_CAP_BYTES = 8 * 1024;

function guardJs() {
  return [
    "#!/usr/bin/env node",
    "import { readFileSync } from 'node:fs';",
    "let raw = '';",
    "try { raw = readFileSync(0, 'utf8'); } catch {}",
    "let commandLine = '';",
    "try {",
    "  const payload = JSON.parse(raw);",
    "  const args = payload?.toolCall?.args ?? {};",
    "  commandLine = String(args.CommandLine ?? args.command ?? payload?.command ?? '');",
    "} catch {}",
    "const patterns = [",
    ...GUARD_PATTERNS.map((re) => `  ${re.toString()},`),
    "];",
    "const matched = Boolean(commandLine) && patterns.some((re) => re.test(commandLine));",
    "const breakGlass = /\\bFLYWHEEL_ALLOW_AM_DOCTOR=1\\b/.test(commandLine) ||",
    "  process.env.FLYWHEEL_ALLOW_AM_DOCTOR === '1';",
    "if (matched && !breakGlass) {",
    `  console.log(JSON.stringify({ decision: 'deny', reason: ${JSON.stringify(DENY_REASON)} }));`,
    "} else {",
    "  console.log(JSON.stringify({ decision: 'allow' }));",
    "}",
  ].join("\n");
}

function startupJs() {
  return [
    "#!/usr/bin/env node",
    "import { spawnSync } from 'node:child_process';",
    `const STARTUP = ${JSON.stringify("__REPO_ROOT__/hooks/startup.js")};`,
    `const CAP = ${STARTUP_CAP_BYTES};`,
    "let text = '';",
    "try {",
    "  const run = spawnSync(process.execPath, [STARTUP], {",
    `    timeout: ${10_000},`,
    "    encoding: 'utf8',",
    "    env: { ...process.env },",
    "  });",
    "  if (run.status === 0 && typeof run.stdout === 'string') text = run.stdout;",
    "} catch {}",
    "text = text.trim();",
    "if (Buffer.byteLength(text, 'utf8') > CAP) {",
    "  const buffer = Buffer.from(text, 'utf8').subarray(0, CAP).toString('utf8');",
    "  text = `${buffer.slice(0, Math.min(buffer.length, buffer.lastIndexOf('\\n') + 1) || CAP)}…[truncated]`;",
    "}",
    "if (!text) {",
    "  console.log(JSON.stringify({}));",
    "} else {",
    "  console.log(JSON.stringify({ injectSteps: [{ systemMessage: { systemMessage: text } }] }));",
    "}",
  ].join("\n");
}

function releaseJs() {
  return [
    "#!/usr/bin/env node",
    "import { spawnSync } from 'node:child_process';",
    `const GUARD = ${JSON.stringify("__REPO_ROOT__/hooks/agent-mail-guard.js")};`,
    "try {",
    "  spawnSync(process.execPath, [GUARD, '--release-reservations'], {",
    `    timeout: ${10_000},`,
    "    stdio: 'ignore',",
    "    env: { ...process.env },",
    "  });",
    "} catch {}",
    "// Never decision:\"continue\" — a Stop hook must not trap the loop.",
    "console.log(JSON.stringify({}));",
    "process.exit(0);",
  ].join("\n");
}

function wrapperSh(helper) {
  return [
    "#!/bin/sh",
    `# Generated by scripts/agy/emit-hooks.mjs — do not edit the installed copy.`,
    `set -u`,
    `dir=\$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)`,
    `exec node "\${dir}/${helper}"`,
    "",
  ].join("\n");
}

/**
 * Translate the Claude hooks document into the AGY flat hooks.json plus the
 * wrapper scripts the handlers point at. Returns:
 *   { hooksJson, files: { "<relpath>": { content, executable } }, unsupported: [{event, reason}] }
 */
export function emitHooks(claudeHooks, { repoRoot }) {
  if (claudeHooks === null || typeof claudeHooks !== "object") {
    throw new TypeError("claudeHooks must be the parsed hooks/hooks.json object");
  }
  if (typeof repoRoot !== "string" || !repoRoot.startsWith("/")) {
    throw new Error(`repoRoot must be an absolute path (got ${JSON.stringify(repoRoot)})`);
  }
  const byEvent = claudeHooks.hooks ?? {};
  const unsupported = [];
  const hooksJson = {};
  const files = {};

  const addWrapper = (name, event, entry, shName, mjsName, jsBody, extra = {}) => {
    files[`hooks/${mjsName}`] = {
      content: jsBody.replaceAll("__REPO_ROOT__", repoRoot),
      executable: false,
    };
    files[`hooks/${shName}`] = { content: wrapperSh(mjsName), executable: true };
    hooksJson[name] = { [event]: [entry], ...extra };
  };

  for (const [event, groups] of Object.entries(byEvent)) {
    if (event === "SessionStart" && Array.isArray(groups)) {
      addWrapper(
        "agent-flywheel-startup",
        "SessionStart",
        { type: "command", command: "./hooks/startup.sh", timeout: 15 },
        "startup.sh",
        "startup.mjs",
        startupJs(),
      );
      continue;
    }
    if (event === "Stop" && Array.isArray(groups)) {
      addWrapper(
        "agent-flywheel-stop",
        "Stop",
        { type: "command", command: "./hooks/release-reservations.sh", timeout: 15 },
        "release-reservations.sh",
        "release-reservations.mjs",
        releaseJs(),
      );
      continue;
    }
    if (event === "PreToolUse" && Array.isArray(groups)) {
      // Claude matcher "Bash" + `if: Bash(*doctor*)` filters become the AGY
      // run_command matcher plus the wrapper's own pattern matching.
      const isBash = groups.some((group) => group?.matcher === "Bash");
      if (isBash) {
        addWrapper(
          "agent-flywheel-guard",
          "PreToolUse",
          {
            matcher: "run_command",
            hooks: [{ type: "command", command: "./hooks/agent-mail-guard.sh", timeout: 10 }],
          },
          "agent-mail-guard.sh",
          "agent-mail-guard.mjs",
          guardJs(),
        );
        continue;
      }
    }
    if (event === "PostToolUse" && Array.isArray(groups)) {
      unsupported.push({
        event,
        matcher: groups[0]?.matcher ?? "*",
        reason:
          "AGY PostToolUse must print a JSON object; the source hook echoes plain text, " +
          "and the AGY-side MCP tool name is not known at sync time.",
      });
      continue;
    }
    if (event === "SubagentStop" && Array.isArray(groups)) {
      unsupported.push({
        event,
        reason: "AGY has no SubagentStop event; the Stop wrapper covers reservation release.",
      });
      continue;
    }
    unsupported.push({
      event,
      reason: `No AGY translation table entry for Claude hook event ${event}.`,
    });
  }

  const serialized = `${JSON.stringify(hooksJson, null, 2)}\n`;
  return { hooksJson, hooksJsonText: serialized, files, unsupported };
}
